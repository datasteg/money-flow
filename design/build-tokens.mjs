// tokens.json -> tokens.css, as Sinho's Implementation section describes: colour and shadow per theme (Day on :root,
// Night under [data-theme="dark"] and, before a choice is saved, prefers-color-scheme), every other family on :root,
// --font-<key> from type.families, and {name} aliases as var(--name).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const val = (v) => (typeof v === 'string' ? v.replace(/^\{([a-z0-9-]+)\}$/, 'var(--$1)') : String(v));
const light = [], dark = [], plain = [];
for (const tok of [...t.color.tokens, ...t.shadow.tokens]) {
  if (typeof tok.value === 'object') { light.push(`  --${tok.name}: ${val(tok.value.light)};`); dark.push(`  --${tok.name}: ${val(tok.value.dark)};`); }
  else light.push(`  --${tok.name}: ${val(tok.value)};`);
}
for (const fam of ['spacing', 'radius', 'layout', 'breakpoint', 'zIndex', 'opacity', 'canvas']) for (const tok of t[fam].tokens) plain.push(`  --${tok.name}: ${val(tok.value)};`);
for (const [k, v] of Object.entries(t.type.families)) plain.push(`  --font-${k}: ${v};`);
const css = `/* Generated by design/build-tokens.mjs from design/tokens.json (Sinho ${t.version}). Do not edit. */
:root {
${light.join('\n')}
${plain.join('\n')}
  color-scheme: light;
}
:root[data-theme="dark"] {
${dark.join('\n')}
  color-scheme: dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${dark.map((l) => '  ' + l).join('\n')}
    color-scheme: dark;
  }
}
`;
writeFileSync(join(here, 'tokens.css'), css);
// sinho.css: the reference component styles without their two remote @imports (the app self-hosts the fonts, and its
// content security policy allows no other origin).
const bundle = readFileSync(join(here, 'bundle.css'), 'utf8').replace(/^@import url\([^)]*\);\s*$/gm, '');
writeFileSync(join(here, 'sinho.css'), `/* Generated by design/build-tokens.mjs from design/bundle.css. Do not edit. */\n${bundle}`);
console.log(`tokens.css: ${light.length + plain.length} tokens, ${dark.length} night overrides`);
